const SITE_LANGUAGE_CODES = { zh: "zh-CN", en: "en", es: "es" };
const SITE_LANGUAGE_STORAGE_KEY = "light-shadow-language";

function getStoredLanguage() {
  try {
    const stored = localStorage.getItem(SITE_LANGUAGE_STORAGE_KEY);
    return SITE_TRANSLATIONS[stored] ? stored : "zh";
  } catch {
    return "zh";
  }
}

function applySiteLanguage(language, announce = false) {
  const lang = SITE_TRANSLATIONS[language] ? language : "zh";
  const translations = SITE_TRANSLATIONS[lang];

  document.documentElement.lang = SITE_LANGUAGE_CODES[lang];
  document.body.dataset.language = lang;
  document.title = translations.pageTitle;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = translations[element.dataset.i18n];
    if (value !== undefined) element.textContent = value;
  });

  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const value = translations[element.dataset.i18nHtml];
    if (value !== undefined) element.innerHTML = value;
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const value = translations[element.dataset.i18nAriaLabel];
    if (value !== undefined) element.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = translations[element.dataset.i18nAlt];
    if (value !== undefined) element.setAttribute("alt", value);
  });

  document.querySelectorAll("[data-i18n-content]").forEach((element) => {
    const value = translations[element.dataset.i18nContent];
    if (value !== undefined) element.setAttribute("content", value);
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    const active = button.dataset.lang === lang;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  const menuToggle = document.querySelector(".menu-toggle");
  const menuLabel = menuToggle?.querySelector(".sr-only");
  if (menuLabel) {
    const open = menuToggle.getAttribute("aria-expanded") === "true";
    menuLabel.textContent = open ? translations.menuClose : translations.menuOpen;
  }

  try {
    localStorage.setItem(SITE_LANGUAGE_STORAGE_KEY, lang);
  } catch {
    // Language switching still works when storage is unavailable.
  }

  if (announce) {
    const status = document.getElementById("language-status");
    if (status) status.textContent = translations.languageChanged;
  }

  window.dispatchEvent(new CustomEvent("site:languagechange", { detail: { language: lang } }));
}

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => applySiteLanguage(button.dataset.lang, true));
});

window.siteI18n = {
  setLanguage: applySiteLanguage,
  getLanguage: () => document.body.dataset.language || "zh",
  translate: (key) => SITE_TRANSLATIONS[document.body.dataset.language || "zh"]?.[key] || key
};

